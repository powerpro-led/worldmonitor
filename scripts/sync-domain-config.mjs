import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = resolve(root, 'shared/domain-config.js');
// Two generated copies: api/*.js can't import shared/ (plain, unbundled JS —
// see api/_cors.js precedent); scripts/*.mjs technically CAN resolve
// ../shared/ locally, but several seed/cron scripts are Railway-deployed
// with rootDirectory: scripts, so the container only has scripts/ copied in
// — a ../shared/ import resolves in dev and crashes at runtime in prod
// (see tests/scripts-railway-nixpacks-no-escape-import.test.mts /
// tests/nixpacks-seeder-import-graph.test.mjs). Every scripts/*.mjs file
// imports the local copy uniformly, whether or not it's Railway-deployed
// today, so this doesn't need re-litigating per script.
//
// scripts/_domain-config.mjs (not .js): scripts/package.json has no
// "type": "module" (it's its own deployable package, defaults to
// CommonJS), unlike api/ which has no package.json of its own and
// inherits the root's "type": "module". A plain .js copy under scripts/
// gets treated as CommonJS by tooling that resolves module format strictly
// from package.json (tsx's loader — confirmed via
// tests/resilience-scores-seed.test.mjs failing with "does not provide an
// export named" until this was renamed), even though plain `node` tolerates
// it via a reparse-as-ESM fallback. `.mjs` sidesteps the ambiguity entirely.
// vscode-extension/sidecar/_domain-config.mjs: local-api-server.mjs lives
// here now (moved from src-tauri/sidecar/ — the VS Code extension's own
// engine, also still bundled as a Tauri resource pending that removal) with
// no shared/ folder alongside it — same "deployed without the rest of the
// repo" problem as scripts/'s Railway deploy, same fix.
//
// scripts/_domain-config.cjs: ais-relay.cjs/notification-relay.cjs are
// CommonJS (scripts/package.json has no "type": "module", and these two
// specifically use `require()`, not the `.mjs` ESM copy the rest of
// scripts/ uses) — a `require()` of an ESM file throws ERR_REQUIRE_ESM, so
// the source can't be copied byte-for-byte like the 3 targets above.
// Mechanically transformed instead: `export function`/`export const` ->
// plain `function`/`const`, plus a generated `module.exports = {...}`
// footer listing every exported name in source order. Safe because
// shared/domain-config.js consistently uses only these two export forms
// (verified: no `export default`, no re-exports, no destructuring) — this
// transform is a plain regex, not a bundler, so it would silently produce
// broken output if that ever changed. sync:domain-config:check catches drift
// the same way as the byte-identical targets.
const cjsTarget = { path: resolve(root, 'scripts/_domain-config.cjs'), label: 'scripts/_domain-config.cjs' };
const GENERATED_TARGETS = [
  { path: resolve(root, 'api/_domain-config.js'), label: 'api/_domain-config.js' },
  { path: resolve(root, 'scripts/_domain-config.mjs'), label: 'scripts/_domain-config.mjs' },
  {
    path: resolve(root, 'vscode-extension/sidecar/_domain-config.mjs'),
    label: 'vscode-extension/sidecar/_domain-config.mjs',
  },
];
const check = process.argv.includes('--check');

const header = `// AUTO-GENERATED by scripts/sync-domain-config.mjs. DO NOT EDIT.\n// Source: shared/domain-config.js\n\n`;
const source = await readFile(sourcePath, 'utf8');
const expected = `${header}${source}`;

function toCjs(esmSource) {
  const exportedNames = [];
  const body = esmSource.replace(/^export (function|const) (\w+)/gm, (_match, kind, name) => {
    exportedNames.push(name);
    return `${kind} ${name}`;
  });
  return `${body}\nmodule.exports = { ${exportedNames.join(', ')} };\n`;
}
const cjsExpected = `${header}${toCjs(source)}`;

if (check) {
  let stale = false;
  for (const { path, label } of GENERATED_TARGETS) {
    const actual = await readFile(path, 'utf8').catch(() => '');
    if (actual !== expected) {
      console.error(`${label} is stale. Run npm run sync:domain-config.`);
      stale = true;
    }
  }
  const actualCjs = await readFile(cjsTarget.path, 'utf8').catch(() => '');
  if (actualCjs !== cjsExpected) {
    console.error(`${cjsTarget.label} is stale. Run npm run sync:domain-config.`);
    stale = true;
  }
  if (stale) process.exitCode = 1;
} else {
  for (const { path, label } of GENERATED_TARGETS) {
    await writeFile(path, expected);
    console.log(`Updated ${label}`);
  }
  await writeFile(cjsTarget.path, cjsExpected);
  console.log(`Updated ${cjsTarget.label}`);
}
